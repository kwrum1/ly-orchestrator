// desiredDataplaneABFAttachScriptFor fakes vppctl for the multi-LAN ABF path.
// omitPolicies makes one LAN report an attach without the expected policies.
func desiredDataplaneABFAttachScriptFor(lans []desiredDataplaneLAN, omitPolicies map[string]bool) string {
	var script strings.Builder
	script.WriteString(`if [ "$*" = "show interface address" ]; then
  printf 'local0 (up):\n  L3 192.168.88.1/24\n'
`)
	for _, lan := range lans {
		address, _, _ := strings.Cut(lan.Address, "/")
		fmt.Fprintf(&script, "  printf '%s (up):\\n  L3 %s/24\\n'\n", lan.Interface, address)
	}
	script.WriteString(`  exit 0
fi
if [ "$*" = "show ly-route dns-intercept" ]; then printf 'enabled 0 fib-index 1\n'; exit 0; fi
`)
	for _, lan := range lans {
		fmt.Fprintf(&script, "if [ \"$*\" = \"show abf attach %s\" ]; then\ncat <<'LY_ROUTE_ABF'\n", lan.Interface)
		script.WriteString("ipv4:\n")
		if !omitPolicies[lan.Interface] {
			for _, id := range vpp.LANDNSABFPolicyIDs(lan.Interface, lan.Address) {
				fmt.Fprintf(&script, " abf-interface-attach: policy:%d priority:1\n", id)
			}
		}
		script.WriteString("LY_ROUTE_ABF\nexit 0\nfi\n")
	}
	script.WriteString("exit 1\n")
	return script.String()
}

