	// the WAN, VPP only owns local0, the lylan-* pair is gone, the dnsmasq
	// drop-in is empty and interception is disabled, yet /health said ok.
	store := desiredDataplaneTestStore(t)
	saveDesiredDataplaneInterface(t, store, "lan-enp2s0", "enp2s0", "lan", "192.168.88.1/24")
	saveDesiredDataplaneInterface(t, store, "wan-enp4s0", "enp4s0", "wan", "10.1.18.25/24")
